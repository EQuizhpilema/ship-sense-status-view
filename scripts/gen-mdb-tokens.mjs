// Regenerates src/lib/mdb-theme-tokens.ts from the live FACTS12 / MDB Bootstrap
// theme sheets, so the isolated MDB cards use the theme's own color and spacing
// tokens instead of hand-written values.
//
//   node scripts/gen-mdb-tokens.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SHEETS = [
  "https://tracking.carrierlogistics.com/carrierlogistics/mdb5/css/mdb.min.css",
  "https://tracking.carrierlogistics.com/carrierlogistics/css/facts12.mdb.css",
];

function customPropsFromRootBlocks(css) {
  const out = [];
  let cursor = 0;
  for (;;) {
    const at = css.indexOf(":root", cursor);
    if (at === -1) break;
    const open = css.indexOf("{", at);
    if (open === -1) break;
    const selector = css.slice(at, open);
    if (selector.includes("dark")) {
      cursor = open + 1;
      continue;
    }
    let depth = 0;
    let close = open;
    for (let i = open; i < css.length; i++) {
      if (css[i] === "{") depth++;
      else if (css[i] === "}") {
        depth--;
        if (depth === 0) {
          close = i;
          break;
        }
      }
    }
    const body = css.slice(open + 1, close);
    for (const m of body.matchAll(/--[a-zA-Z0-9_-]+\s*:\s*[^;{}]+/g)) {
      out.push(`${m[0].replace(/\s+/g, " ").trim()};`);
    }
    cursor = close + 1;
  }
  return out;
}

const texts = await Promise.all(
  SHEETS.map(async (url) => {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
    return res.text();
  }),
);

const all = texts.flatMap(customPropsFromRootBlocks);

// Later sheets must win, so keep only the last declaration of each token.
const seen = new Set();
const ordered = [];
for (const decl of [...all].reverse()) {
  const name = decl.split(":")[0];
  if (seen.has(name)) continue;
  seen.add(name);
  ordered.push(decl);
}
ordered.reverse();

const tokens = ordered.join("");
const header = `// GENERATED by scripts/gen-mdb-tokens.mjs - do not edit by hand.
// Custom properties lifted out of the FACTS12 / MDB Bootstrap theme sheets
// (MDB_STYLESHEETS in src/lib/mdb-theme.ts) so they can be re-declared on
// :host inside a shadow root, where the sheets' own :root selector cannot match.
`;

const target = fileURLToPath(new URL("../src/lib/mdb-theme-tokens.ts", import.meta.url));
writeFileSync(
  target,
  `${header}export const MDB_THEME_TOKENS =\n  ${JSON.stringify(tokens)};\n`,
);
console.log(`${ordered.length} tokens, ${tokens.length} chars -> ${target}`);
